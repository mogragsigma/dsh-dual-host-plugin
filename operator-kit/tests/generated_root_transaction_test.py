import sys,unittest
from pathlib import Path
from unittest.mock import patch
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'scripts'))
from upgrade_plan import plan,PlanError
import install_transaction_test as fixtures
from generated_root_test import CONTRACT

class GeneratedRootTransaction(fixtures.Transaction):
 def setup_cached(self):
  self.setup_install();self.root_file=self.profile/'cordis.yml'
  self.cache='- name: '+str(self.old/'native-entry.js')+'\n'
  self.root_file.write_text(self.cache)
  self.addCleanup(patch.stopall);patch('upgrade_plan.profile_root_contract',return_value=CONTRACT).start()
  self.planned=plan(self.home,'fixture',self.new)
 def test_host_regeneration_is_not_restored_over_or_mistaken_for_source_drift(self):
  self.setup_cached();tx=self.prepared();self.run_apply(tx)
  self.assertEqual(self.root_file.read_text(),self.cache)
  regenerated='# regenerated by the real host in integration coverage\n[]\n';self.root_file.write_text(regenerated)
  self.run_rollback(tx);self.assertEqual(self.root_file.read_text(),regenerated)
  self.assertEqual((self.profile/'cordis.patch.yml').read_bytes(),self.originals['profiles/fixture/cordis.patch.yml'])
 def test_runtime_contract_changes_block_before_installation(self):
  self.setup_cached();tx=self.prepared()
  with patch('upgrade_plan.profile_root_contract',return_value={**CONTRACT,'startupSourceSha256':'changed'}),self.assertRaisesRegex(PlanError,'PROFILE_ROOT_CONTRACT_CHANGED'):self.run_apply(tx)
  self.assertEqual(self.root_file.read_text(),self.cache);self.assertFalse((self.home/'task-gateway/v0.24.0-alpha.2').exists())
 def test_new_home_override_after_prepare_cannot_enter_unreviewed(self):
  self.setup_cached();tx=self.prepared();p=self.home/'cordis.patch.yml';p.write_text('- update: task-gateway\n')
  with self.assertRaisesRegex(PlanError,'UNRELATED_INPUT_CHANGED'):self.run_apply(tx)
  self.assertFalse((self.home/'task-gateway/v0.24.0-alpha.2').exists());self.assertEqual(self.root_file.read_text(),self.cache)
 def test_generated_root_link_change_does_not_become_permission_to_read_elsewhere(self):
  self.setup_cached();tx=self.prepared();self.root_file.unlink();self.root_file.symlink_to(self.old/'native-entry.js')
  with self.assertRaisesRegex(PlanError,'SYMLINK_PATH'):self.run_apply(tx)
  self.assertFalse((self.home/'task-gateway/v0.24.0-alpha.2').exists())

for base in fixtures.Transaction.__mro__:
 for name in base.__dict__:
  if name.startswith('test_') and name not in GeneratedRootTransaction.__dict__:setattr(GeneratedRootTransaction,name,None)
if __name__=='__main__':unittest.main()
